// Normalize Urdu & bilingual text for clean matching
export function normalizeUrduText(text) {
  if (!text || typeof text !== 'string') return '';
  return text
    .toLowerCase()
    .replace(/[\u200B-\u200F\uFEFF]/g, '')
    .replace(/[؟?!\.,،:؛\-_()[\]{}"'`~\\/|—–]/g, ' ')
    .replace(/[يى]/g, 'ی')
    .replace(/[ك]/g, 'ک')
    .replace(/[ةۃۀ]/g, 'ہ')
    .replace(/[ؤ]/g, 'و')
    .replace(/[إأآٱ]/g, 'ا')
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/\b(طلبہ|طلبا)\b/g, 'طلباء')
    .replace(/\s+/g, ' ')
    .trim();
}

