function canonicalizeText(normText) {
  if (!normText) return '';
  let text = ` ${normText} `;
  for (const [src, target] of CANONICAL_REPLACEMENTS) {
    const normSrc = normalizeUrduText(src);
    if (!normSrc) continue;
    text = text.split(` ${normSrc} `).join(` ${target} `);
  }
  const tokens = text
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map(tok => TOKEN_SYNONYMS[tok] || tok);
  return tokens.join(' ');
}

function containsWholePhrase(haystack, needle) {
  if (!haystack || !needle) return false;
  return ` ${haystack} `.includes(` ${needle} `);
}

